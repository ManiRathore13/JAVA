        //AND OPERATOR
public class Logical {
    public static void main(String[] args) {
        int a=10;
        int b=20;
        int c=10;
        System.out.println(a<b&&b>c);
        //OR OPERATOR
        int d=10;
        int e=20;
        int f=25;
        System.out.println(d>e || f>e);

        //NOT OPERATOR
        int g=10;
        int h=20;
        System.out.println(!(g<h));

    }
    
}
